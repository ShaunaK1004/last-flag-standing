#!/usr/bin/env python3
"""
winart_pack.py - put winner-screen art into the site folder and keep the manifest up to date.

The game never embeds art. It reads  winart/manifest.js  (one small script) and fetches each
country's images only when that country reaches the final few of a round.

  winart/
    manifest.json        source of truth (edited only by this tool)
    manifest.js          the same data as  window.WINART_MANIFEST = {...}  (what the game loads)
    c/<code>/            one folder per poster country:  bg / body / flag / beast / title  (.webp)
    kits/<kit>/          shared warrior + beast kits for the long tail:  body / flag (shade map) / beast
    bg/<name>-<hash>.webp  shared backgrounds (with the poster HUD frames baked in, no characters)

Every image file name carries a content hash (body-1a2b3c4d.webp), so Vercel can cache it forever
and a re-cut never shows a stale copy. Old files of the same slot are deleted when replaced.

Commands (run from anywhere; paths are relative to where you run it):
  poster  RU  winart_ru_vertical.json  [--bg V_bg.png] [--beast bear]
          Adds/replaces a poster country from build_vertical.py output. bodyFade/bearFade are
          dropped (the game makes them at load time from the 'fade' ranges).
  kit     NAME  --dir folder_with(body.png, beast.png, flagshade.png, meta.json)  [--beast bear]
  bg      NAME  image.png              shared background (941x1672 poster size)
  map     CODE  --kit NAME --bg NAME [--test-only]      long-tail country -> kit + background
  unmap   CODE
  remove  CODE                         removes a poster country and its folder
  list
"""
import argparse, base64, hashlib, io, json, os, re, shutil, sys, datetime
from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
WA = os.path.join(ROOT, 'winart')
MAN = os.path.join(WA, 'manifest.json')

LAYOUT = {   # poster HUD layout shared by every Flags Rumble poster (poster px, 941 x 1672)
    'grid': {'x0': 62, 'dx': 50.8, 'y0': 1332, 'dy': 34.4, 'r': 15.5, 'cols': 17, 'rows': 4},
    'text': {'countries': [526, 71], 'cycle': [471, 122], 'stats': [470, 1237], 'elimtxt': [470, 1496]},
}

def load():
    if os.path.exists(MAN):
        with open(MAN) as f: m = json.load(f)
    else:
        m = {}
    m.setdefault('format', 2); m.setdefault('layout', LAYOUT)
    for k in ('posters', 'kits', 'bgs', 'kitCountries'): m.setdefault(k, {})
    return m

def save(m):
    os.makedirs(WA, exist_ok=True)
    m['updated'] = datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ')
    for k in ('posters', 'kits', 'bgs', 'kitCountries'): m[k] = dict(sorted(m[k].items()))
    hbp = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'cut', 'handlebox.json')   # @handle banner spots (cut/handle_box.py)
    if os.path.exists(hbp):
        for key, box in json.load(open(hbp)).items():
            for grp in ('posters', 'kits'):
                if key in m[grp]: m[grp][key]['hb'] = box
    with open(MAN, 'w') as f: json.dump(m, f, indent=1)
    with open(os.path.join(WA, 'manifest.js'), 'w') as f:
        f.write('/* generated by tools/winart_pack.py - do not edit by hand */\n')
        f.write('window.WINART_MANIFEST=' + json.dumps(m, separators=(',', ':')) + ';\n')
    print('manifest:', len(m['posters']), 'poster countries,', len(m['kits']), 'kits,', len(m['bgs']), 'backgrounds,',
          len(m['kitCountries']), 'kit countries')

def h8(b): return hashlib.sha1(b).hexdigest()[:8]

def enc(img, q):
    b = io.BytesIO(); img.save(b, 'WEBP', quality=q, method=6); return b.getvalue()

def write(rel_dir, slot, data, ext='webp'):
    """write winart/<rel_dir>/<slot>-<hash>.<ext>, delete older files of the same slot, return path rel. to winart/"""
    d = os.path.join(WA, rel_dir); os.makedirs(d, exist_ok=True)
    name = f'{slot}-{h8(data)}.{ext}'
    for old in os.listdir(d):
        if re.fullmatch(re.escape(slot) + r'-[0-9a-f]{8}\.\w+', old) and old != name: os.remove(os.path.join(d, old))
    with open(os.path.join(d, name), 'wb') as f: f.write(data)
    return f'{rel_dir}/{name}'

def bbox_layer(img):
    a = img.split()[-1]; bb = a.point(lambda v: 255 if v > 4 else 0).getbbox()
    return bb, img.crop(bb)

# ------------------------------------------------------------------ commands
def cmd_poster(a):
    code = a.code.upper(); src = json.load(open(a.json))
    m = load(); d = f'c/{code.lower()}'; L = {}; total = 0
    rename = {'bear': 'beast'}
    for k, v in src['layers'].items():
        if k.endswith('Fade'): continue                       # made at runtime from 'fade'
        head, b64 = v['src'].split(',', 1); raw = base64.b64decode(b64)
        if k == 'bg':
            if a.bg: raw = enc(Image.open(a.bg).convert('RGB'), 82)
            elif 'jpeg' in head: raw = enc(Image.open(io.BytesIO(raw)).convert('RGB'), 84)
        slot = rename.get(k, k)
        L[slot] = {'x': v['x'], 'y': v['y'], 'w': v['w'], 'h': v['h'], 'f': write(d, slot, raw)}
        total += len(raw)
    an = dict(src['anchors']); an['beastPivot'] = an.pop('bearPivot', an.get('beastPivot'))
    e = {'beast': a.beast or src.get('beast') or 'bear', 'w': src['w'], 'h': src['h'], 'layers': L, 'anchors': an,
         'fade': src.get('fade', {'body': [720, 832], 'beast': [590, 760]})}
    if src.get('cls'):                                     # layout B (title + logo + stats bar): own text spots, no grid
        e['layout'] = 'B'; e['text'] = src['text']
        for k in ('cls', 'fx', 'color', 'amb', 'petal', 'dir', 'enter'):
            if src.get(k) is not None: e[k] = src[k]
    else:
        if src.get('grid') and src['grid'] != m['layout']['grid']: e['grid'] = src['grid']
        if src.get('text') and src['text'] != m['layout']['text']: e['text'] = src['text']
    m['posters'][code] = e; m['kitCountries'].pop(code, None); save(m)
    print(f'{code}: {total // 1024} KB in {len(L)} files')

def cmd_kitb(a):
    """layout-B kit from build_kit.py output (kit_<code>.json)"""
    name = a.name.lower(); src = json.load(open(a.json)); m = load(); d = f'kits/{name}'; L = {}; total = 0
    for k, v in src['layers'].items():
        head, b64 = v['src'].split(',', 1); raw = base64.b64decode(b64)
        if k == 'bg':
            raw = enc(Image.open(a.bg).convert('RGB'), 82) if a.bg else enc(Image.open(io.BytesIO(raw)).convert('RGB'), 84)
        slot = {'bear': 'beast'}.get(k, k)
        if slot == 'wmap': raw_ = raw
        L[slot] = {'x': v['x'], 'y': v['y'], 'w': v['w'], 'h': v['h'], 'f': write(d, slot, raw)}; total += len(raw)
    an = dict(src['anchors']); an['beastPivot'] = an.pop('bearPivot', an.get('beastPivot'))
    e = {'layout': 'B', 'beast': a.beast or src.get('beast') or 'bear', 'w': src['w'], 'h': src['h'], 'layers': L, 'anchors': an,
         'fade': src.get('fade'), 'text': src['text'], 'flagCols': src['flagCols'], 'flagColStep': src['flagColStep'], 'ball': src['ball'], 'band': src['band']}
    for k in ('cls', 'fx', 'color', 'amb', 'petal', 'dir'):
        if src.get(k) is not None: e[k] = src[k]
    if m['kits'].get(name, {}).get('clan'): e['clan'] = m['kits'][name]['clan']        # keep the clan banner
    m['kits'][name] = e; save(m); print(f'kitB {name}: {total // 1024} KB')

def cmd_clan(a):
    """clan banner (640x480) for the generic champion card of a kit (made by cut/clan_flag.py)"""
    name = a.name.lower(); m = load()
    if name not in m['kits']: sys.exit('no kit ' + name)
    raw = enc(Image.open(a.image).convert('RGB').resize((640, 480)), 88)
    m['kits'][name]['clan'] = {'f': write(f'kits/{name}', 'clan', raw), 'w': 640, 'h': 480}; save(m); print(f'clan {name}: {len(raw) // 1024} KB')

def cmd_mapb(a):
    """map many countries to a layout-B kit: mapb KIT CODE CODE ..."""
    m = load(); kit = a.kit.lower()
    if kit not in m['kits']: sys.exit('no kit ' + kit)
    for c in a.codes:
        c = c.upper()
        if c in m['posters']: print('skip (has poster)', c); continue
        m['kitCountries'][c] = {'kit': kit}
    save(m)

def cmd_kit(a):
    name = a.name.lower(); d = f'kits/{name}'; src = a.dir
    meta = json.load(open(os.path.join(src, 'meta.json')))
    m = load(); L = {}; total = 0
    for slot, fn in (('body', 'body.png'), ('beast', 'beast.png'), ('flag', 'flagshade.png'), ('plate', 'plate.png')):
        if slot == 'plate' and not os.path.exists(os.path.join(src, fn)): continue   # optional title plate
        img = Image.open(os.path.join(src, fn)).convert('RGBA')
        off = meta.get('offsets', {}).get(slot)            # layer already cropped: its poster x,y
        if off: bb = (off[0], off[1], off[0] + img.width, off[1] + img.height); crop = img
        else: bb, crop = bbox_layer(img)
        raw = enc(crop, 90 if slot == 'flag' else 86)
        L[slot] = {'x': bb[0], 'y': bb[1], 'w': bb[2] - bb[0], 'h': bb[3] - bb[1], 'f': write(d, slot, raw)}
        total += len(raw)
    e = {'beast': a.beast or meta.get('beast', 'bear'), 'w': 941, 'h': 1672, 'layers': L, 'anchors': meta['anchors'],
         'fade': meta.get('fade', {'body': [720, 832], 'beast': [590, 760]}), 'flagCols': meta['flagCols'],
         'flagColStep': meta.get('flagColStep', 4), 'title': meta['title']}
    m['kits'][name] = e; save(m); print(f'kit {name}: {total // 1024} KB')

def cmd_bg(a):
    name = a.name.lower(); m = load()
    img = Image.open(a.image).convert('RGB')
    if img.size != (941, 1672): img = img.resize((941, 1672), Image.LANCZOS)
    raw = enc(img, 82); f = write('bg', name, raw)
    m['bgs'][name] = {'f': f}; save(m); print(f'bg {name}: {len(raw) // 1024} KB')

def cmd_map(a):
    code = a.code.upper(); m = load()
    if a.kit not in m['kits']: sys.exit(f'no kit "{a.kit}" - add it first')
    if a.bg not in m['bgs']: sys.exit(f'no background "{a.bg}" - add it first')
    if code in m['posters']: sys.exit(f'{code} already has its own poster - remove it first')
    e = {'kit': a.kit, 'bg': a.bg}
    if a.test_only: e['testOnly'] = True
    m['kitCountries'][code] = e; save(m)

def cmd_unmap(a):
    m = load(); m['kitCountries'].pop(a.code.upper(), None); save(m)

def cmd_remove(a):
    code = a.code.upper(); m = load()
    if m['posters'].pop(code, None) is not None:
        shutil.rmtree(os.path.join(WA, 'c', code.lower()), ignore_errors=True)
    save(m)

def cmd_list(a):
    m = load()
    def size(files):
        return sum(os.path.getsize(os.path.join(WA, f)) for f in files if os.path.exists(os.path.join(WA, f))) // 1024
    for c, e in m['posters'].items(): print(f'poster {c:3} {e["beast"]:8} {size(v["f"] for v in e["layers"].values()):5} KB')
    for k, e in m['kits'].items(): print(f'kit    {k:12} {e["beast"]:8} {size(v["f"] for v in e["layers"].values()):5} KB')
    for k, e in m['bgs'].items(): print(f'bg     {k:12} {size([e["f"]]):5} KB')
    for c, e in m['kitCountries'].items(): print(f'kit-country {c} -> kit {e["kit"]}, bg {e["bg"]}' + (' (test only)' if e.get('testOnly') else ''))

if __name__ == '__main__':
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    s = p.add_subparsers(dest='cmd', required=True)
    x = s.add_parser('poster'); x.add_argument('code'); x.add_argument('json'); x.add_argument('--bg'); x.add_argument('--beast'); x.set_defaults(f=cmd_poster)
    x = s.add_parser('kit'); x.add_argument('name'); x.add_argument('--dir', required=True); x.add_argument('--beast'); x.set_defaults(f=cmd_kit)
    x = s.add_parser('kitb'); x.add_argument('name'); x.add_argument('json'); x.add_argument('--bg'); x.add_argument('--beast'); x.set_defaults(f=cmd_kitb)
    x = s.add_parser('clan'); x.add_argument('name'); x.add_argument('image'); x.set_defaults(f=cmd_clan)
    x = s.add_parser('mapb'); x.add_argument('kit'); x.add_argument('codes', nargs='+'); x.set_defaults(f=cmd_mapb)
    x = s.add_parser('bg'); x.add_argument('name'); x.add_argument('image'); x.set_defaults(f=cmd_bg)
    x = s.add_parser('map'); x.add_argument('code'); x.add_argument('--kit', required=True); x.add_argument('--bg', required=True); x.add_argument('--test-only', action='store_true'); x.set_defaults(f=cmd_map)
    x = s.add_parser('unmap'); x.add_argument('code'); x.set_defaults(f=cmd_unmap)
    x = s.add_parser('remove'); x.add_argument('code'); x.set_defaults(f=cmd_remove)
    x = s.add_parser('list'); x.set_defaults(f=cmd_list)
    x = s.add_parser('resave', help='re-write the manifest (e.g. after cut/handle_box.py)'); x.set_defaults(f=lambda a: save(load()))
    a = p.parse_args(); a.f(a)
    if a.cmd != 'list':
        import winart_local; winart_local.build()   # keep the double-click test copy in step
